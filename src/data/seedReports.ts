import { Report, StatusHistoryItem } from '../types';
import { calculatePriorityScore, computeDurationScore } from '../utils/priority';

// Helper to construct seeded report with deterministic factors and priority score
function createSeedReport(data: {
  id: string;
  title: string;
  description: string;
  category: Report['category'];
  latitude: number;
  longitude: number;
  areaName: string;
  landmark?: string;
  status: Report['status'];
  severity: number;
  recurrence: number;
  communityImpact: number;
  daysAgo: number;
  imageUrl?: string;
  duplicateCandidateIds?: string[];
  keywords: string[];
  recommendedAction: string;
}): Report {
  const now = new Date();
  const createdDate = new Date(now.getTime() - data.daysAgo * 24 * 60 * 60 * 1000);
  const updatedDate = new Date(createdDate.getTime() + Math.min(data.daysAgo, 2) * 24 * 60 * 60 * 1000);
  const resolvedDate = data.status === 'resolved' ? new Date(now.getTime() - 1 * 24 * 60 * 60 * 1000).toISOString() : undefined;

  const durationInfo = computeDurationScore(createdDate);

  const priorityResult = calculatePriorityScore({
    severity: data.severity,
    recurrence: data.recurrence,
    durationDays: durationInfo.days,
    durationScore: durationInfo.score,
    communityImpact: data.communityImpact,
  });

  const statusHistory: StatusHistoryItem[] = [
    {
      status: 'submitted',
      timestamp: createdDate.toISOString(),
      updatedBy: 'Citizen Reporter',
      note: 'Civic complaint recorded with geo-coordinates and photo evidence.',
    },
  ];

  if (data.status === 'under_review' || data.status === 'in_progress' || data.status === 'resolved') {
    statusHistory.push({
      status: 'under_review' as const,
      timestamp: new Date(createdDate.getTime() + 12 * 60 * 60 * 1000).toISOString(),
      updatedBy: 'GHMC Ward Engineering Cell',
      note: 'Complaint validated by municipal zone officer. Site inspection queued.',
    });
  }

  if (data.status === 'in_progress' || data.status === 'resolved') {
    statusHistory.push({
      status: 'in_progress' as const,
      timestamp: new Date(createdDate.getTime() + 36 * 60 * 60 * 1000).toISOString(),
      updatedBy: 'Zonal Maintenance Contractor',
      note: 'Remediation crew dispatched with repair equipment.',
    });
  }

  if (data.status === 'resolved') {
    statusHistory.push({
      status: 'resolved' as const,
      timestamp: resolvedDate || now.toISOString(),
      updatedBy: 'Assistant Municipal Engineer',
      note: 'Civic hazard rectified and cleared. Post-repair photo verified.',
    });
  }

  return {
    id: data.id,
    title: data.title,
    description: data.description,
    category: data.category,
    latitude: data.latitude,
    longitude: data.longitude,
    areaName: data.areaName,
    landmark: data.landmark,
    imageUrl: data.imageUrl,
    status: data.status,
    severity: data.severity,
    priorityScore: priorityResult.score,
    priorityBand: priorityResult.band,
    priorityFactors: priorityResult.factors,
    duplicateCandidateIds: data.duplicateCandidateIds || [],
    aiAnalysis: {
      category: data.category,
      severity: data.severity,
      confidence: 0.92,
      summary: data.title,
      keywords: data.keywords,
      recommendedAction: data.recommendedAction,
      isFallback: false,
      modelUsed: 'gemini-3.8-flash',
      reasoningFactors: [
        `High impact on ${data.areaName} arterial corridor`,
        `Identified category: ${data.category}`,
        `Reported age: ${data.daysAgo} days without permanent closure`,
      ],
    },
    statusHistory,
    isDemo: true,
    createdAt: createdDate.toISOString(),
    updatedAt: updatedDate.toISOString(),
    resolvedAt: resolvedDate,
  };
}

